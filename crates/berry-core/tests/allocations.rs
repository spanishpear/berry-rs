//! Allocation counts of the parse APIs, measured with a counting global
//! allocator.
//!
//! * `parse_with` + recycled buffers: zero allocations.
//! * `parse`: a constant number (the segment list and the seven table
//!   buffers), independent of the number of entries, chunks and threads.
//!
//! Everything runs in one `#[test]` so no other test allocates concurrently.

use berry::Buffers;
use std::alloc::{GlobalAlloc, Layout, System};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering::Relaxed};

struct Counting;

static ENABLED: AtomicBool = AtomicBool::new(false);
static ALLOCS: AtomicUsize = AtomicUsize::new(0);
static REALLOCS: AtomicUsize = AtomicUsize::new(0);

// SAFETY: every method forwards to `System` with the caller's arguments
// unchanged, so `System`'s guarantees carry over; the counters are atomics and
// never allocate.
unsafe impl GlobalAlloc for Counting {
  unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
    if ENABLED.load(Relaxed) {
      ALLOCS.fetch_add(1, Relaxed);
    }
    // SAFETY: forwarded unchanged; the caller upholds `GlobalAlloc::alloc`'s contract.
    unsafe { System.alloc(layout) }
  }

  unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
    if ENABLED.load(Relaxed) {
      ALLOCS.fetch_add(1, Relaxed);
    }
    // SAFETY: forwarded unchanged; the caller upholds the `alloc_zeroed` contract.
    unsafe { System.alloc_zeroed(layout) }
  }

  unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
    // SAFETY: `ptr` was allocated by `System` (all allocations go through it)
    // with `layout`, as the caller guarantees.
    unsafe { System.dealloc(ptr, layout) }
  }

  unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
    if ENABLED.load(Relaxed) {
      REALLOCS.fetch_add(1, Relaxed);
    }
    // SAFETY: as for `dealloc`; `new_size` is forwarded unchanged.
    unsafe { System.realloc(ptr, layout, new_size) }
  }
}

#[global_allocator]
static GLOBAL: Counting = Counting;

/// (allocations, reallocations) performed by `f`.
fn count<T>(f: impl FnOnce() -> T) -> ((usize, usize), T) {
  ALLOCS.store(0, Relaxed);
  REALLOCS.store(0, Relaxed);
  ENABLED.store(true, Relaxed);
  let out = std::hint::black_box(f());
  ENABLED.store(false, Relaxed);
  ((ALLOCS.load(Relaxed), REALLOCS.load(Relaxed)), out)
}

fn fixtures() -> Vec<(String, String)> {
  let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../fixtures");
  let mut v: Vec<_> = std::fs::read_dir(&dir)
    .unwrap()
    .filter_map(|e| {
      let p = e.ok()?.path();
      (p.extension()? == "lock").then(|| {
        let name = p.file_name().unwrap().to_string_lossy().into_owned();
        (name, std::fs::read_to_string(&p).unwrap())
      })
    })
    .collect();
  v.sort();
  v
}

const HEAD: &str = "# This file is generated by running \"yarn install\" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10\n\n";

/// A ~6 MB input (the largest fixture's body three times), parsed in
/// parallel.
fn large(fixtures: &[(String, String)]) -> String {
  let src = &fixtures
    .iter()
    .find(|(n, _)| n == "resolutions-patches.yarn.lock")
    .unwrap()
    .1;
  let body_at = src.find("\n\n\"").unwrap() + 2;
  let (head, body) = src.split_at(body_at);
  format!("{head}{body}\n{body}\n{body}")
}

/// The parallel parse: the same constant number as a sequential parse (the
/// chunks share one buffer per table), no growth, and nothing at all with
/// recycled buffers.
fn parallel_parse_allocations(src: &str) {
  // Start the pool first: its threads allocate when they start.
  let lockfile = berry::parse(src).unwrap();
  let k = lockfile.__segments();
  drop(lockfile);
  if std::thread::available_parallelism().map_or(1, usize::from) > 1 {
    assert!(k > 1, "the large input must be split");
  }
  let ((allocs, reallocs), lockfile) = count(|| berry::parse(src).unwrap());
  assert_eq!(lockfile.__segments(), k);
  assert_eq!(lockfile.__spills(), 0, "no chunk outgrew its windows");
  assert!(
    allocs <= 1 + 7,
    "fresh parallel parse: {allocs} allocations for {k} chunks"
  );
  assert_eq!(reallocs, 0, "fresh parallel parse: {k} chunks");
  drop(lockfile);

  let mut buffers = Buffers::new();
  buffers = berry::parse_with(src, &mut buffers).unwrap().into_buffers();
  let ((allocs, reallocs), lockfile) = count(|| berry::parse_with(src, &mut buffers).unwrap());
  assert_eq!((allocs, reallocs), (0, 0), "recycled parallel parse");
  drop(lockfile);
}

#[test]
fn allocation_counts() {
  let mut buffers = Buffers::new();
  for (name, src) in fixtures() {
    let lockfile = berry::parse(&src).unwrap();
    let entries = lockfile.len();
    drop(lockfile);

    // Warm the buffers, then a second parse must not allocate at all.
    let lockfile = berry::parse_with(&src, &mut buffers).unwrap();
    buffers = lockfile.into_buffers();
    let ((allocs, reallocs), lockfile) = count(|| berry::parse_with(&src, &mut buffers).unwrap());
    assert_eq!((allocs, reallocs), (0, 0), "{name}: recycled parse");
    assert_eq!(lockfile.len(), entries);
    buffers = lockfile.into_buffers();

    // A fresh parse: the segment list and the seven table buffers, none of
    // which grows.
    let ((allocs, reallocs), lockfile) = count(|| berry::parse(&src).unwrap());
    assert!(
      allocs <= 1 + 7,
      "{name}: fresh parse made {allocs} allocations"
    );
    assert_eq!(reallocs, 0, "{name}: fresh parse reallocated");
    drop(lockfile);
  }

  parallel_parse_allocations(&large(&fixtures()));
  let small = format!("{HEAD}\"a@npm:1\":\n  version: 1\n");
  let ((allocs, _), _) = count(|| berry::parse(&small).unwrap());
  assert!(allocs <= 1 + 7, "small parse: {allocs} allocations");
}
