//! Inputs at the `u32` size limit of the span index.
//!
//! Ignored by default: each case builds a ~4 GiB string (about 4.3 GB of RAM).
//! Run with `cargo test --release -p berry-test --test size_limit -- --ignored`.

use berry::ErrorKind;

const HEAD: &str = "# This file is generated by running \"yarn install\" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10\n\n\"a@npm:1\":\n  checksum: ";

/// An entry whose `checksum` pads the input to `total` bytes, ending with
/// `  {field}: ""` and no final newline (an empty span at EOF).
fn padded(total: usize, field: &str) -> String {
  let tail = format!("\n  {field}: \"\"");
  let mut s = String::with_capacity(total);
  s.push_str(HEAD);
  s.extend(std::iter::repeat_n('x', total - HEAD.len() - tail.len()));
  s.push_str(&tail);
  assert_eq!(s.len(), total);
  s
}

/// Regression: at exactly `u32::MAX` bytes the empty span at EOF started at
/// `u32::MAX`, the "absent" marker, so `version: ""` / `resolution: ""` came
/// back as `None` (berry 0.6: `Some("")`). Such inputs are now rejected with
/// `InputTooLarge`; one byte less parses and keeps the field.
#[test]
#[ignore = "builds 4 GiB inputs"]
fn u32_max_input_keeps_empty_fields() {
  for field in ["version", "resolution"] {
    for total in [u32::MAX as usize, u32::MAX as usize - 1] {
      let src = padded(total, field);
      match berry::parse(&src) {
        Ok(lockfile) => {
          assert!(total < u32::MAX as usize);
          assert_eq!(lockfile.remaining(), "");
          let e = lockfile.entry(0).unwrap();
          let got = if field == "version" {
            e.version()
          } else {
            e.resolution()
          };
          assert_eq!(got, Some(""), "{field} at {total}");
        }
        Err(e) => {
          assert_eq!(total, u32::MAX as usize);
          assert_eq!(e.kind(), ErrorKind::InputTooLarge);
        }
      }
    }
  }
}
