//! Direct field-level assertions on hand-written synthetic lockfiles.

use berry::LinkType;

const FULL: &str = r#"# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"alpha@npm:^1.0.0, alpha@npm:^1.1.0":
  version: 1.2.0
  resolution: "alpha@npm:1.2.0"
  dependencies:
    beta: "npm:^2.0.0"
    "@sc/gamma": "npm:3.0.0"
  peerDependencies:
    delta: ^4
  peerDependenciesMeta:
    delta:
      optional: true
  dependenciesMeta:
    beta:
      built: false
      optional: true
      unplugged: true
  bin:
    alpha-cli: ./bin/cli.js
  conditions: os=linux & cpu=x64
  checksum: 10c0/deadbeef
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft
"#;

#[test]
fn every_field_of_a_full_entry_is_parsed() {
  let lf = berry::parse(FULL).expect("parse");
  assert!(lf.remaining().trim().is_empty());
  assert_eq!(lf.metadata().version, "8");
  assert_eq!(lf.metadata().cache_key, "10c0");
  assert_eq!(lf.len(), 2);

  let e = lf.entry(0).unwrap();
  assert_eq!(e.descriptors().len(), 2);
  assert_eq!(
    e.descriptors()
      .iter()
      .map(|d| d.to_string())
      .collect::<Vec<_>>(),
    ["alpha@npm:^1.0.0", "alpha@npm:^1.1.0"]
  );
  assert_eq!(e.version(), Some("1.2.0"));
  assert_eq!(e.resolution(), Some("alpha@npm:1.2.0"));
  let loc = e.resolution_locator().unwrap();
  assert_eq!(
    (loc.ident().as_str(), loc.reference()),
    ("alpha", "npm:1.2.0")
  );
  assert_eq!(e.language_name(), "node");
  assert_eq!(e.link_type(), LinkType::Hard);
  assert_eq!(e.checksum(), Some("10c0/deadbeef"));
  assert_eq!(e.conditions(), Some("os=linux & cpu=x64"));
  assert_eq!(e.dependencies().len(), 2);
  let gamma = e.dependencies().get("@sc/gamma").unwrap();
  assert_eq!(
    (gamma.ident().scope(), gamma.ident().name(), gamma.range()),
    (Some("@sc"), "gamma", "npm:3.0.0")
  );
  assert_eq!(e.peer_dependencies().len(), 1);
  assert_eq!(e.peer_dependencies().get("delta").unwrap().range(), "^4");
  assert_eq!(e.peer_dependencies_meta().len(), 1);
  assert!(e.peer_dependencies_meta().get("delta").unwrap().optional);
  assert_eq!(e.dependencies_meta().len(), 1);
  let m = e.dependencies_meta().get("beta").unwrap();
  assert_eq!(
    (m.built, m.optional, m.unplugged),
    (Some(false), Some(true), Some(true))
  );
  assert_eq!(e.bin().get("alpha-cli"), Some("./bin/cli.js"));

  let w = lf.entry(1).unwrap();
  assert_eq!(w.link_type(), LinkType::Soft);
  assert_eq!(w.language_name(), "unknown");
  assert_eq!(w.checksum(), None);
  assert!(w.dependencies().is_empty());
  assert!(w.dependencies().last_wins().next().is_none());
}

#[test]
fn crlf_and_missing_final_newline_do_not_change_fields() {
  let a = berry::parse(FULL).expect("lf");
  let crlf = FULL.replace('\n', "\r\n");
  let noeol = FULL.trim_end();
  for src in [crlf.as_str(), noeol] {
    // Either parses to identical fields or fails; the differential suite
    // pins which. Here we only require no field drift when it parses.
    if let Ok(b) = berry::parse(src) {
      assert_eq!(a.len(), b.len());
      assert_eq!(a.metadata().cache_key, b.metadata().cache_key);
      for (x, y) in a.entries().zip(b.entries()) {
        assert_eq!(x.version(), y.version());
        assert_eq!(x.checksum(), y.checksum());
        assert_eq!(x.conditions(), y.conditions());
        assert_eq!(x.link_type(), y.link_type());
      }
    }
  }
}

#[test]
fn bad_input_returns_error_instead_of_panicking() {
  let bad_link = FULL.replace("linkType: hard", "linkType: sideways");
  let unknown = FULL.replace("languageName: node", "languageName: node\n  frobnicate: 1");
  for src in [bad_link, unknown] {
    let r = std::panic::catch_unwind(|| berry::parse(&src).is_err());
    assert_eq!(r.ok(), Some(true), "must return Err, not panic");
  }
}

#[test]
fn empty_and_header_only_inputs_do_not_panic() {
  for src in [
    "",
    "\n",
    "# comment only\n",
    "__metadata:\n  version: 8\n  cacheKey: 1\n",
  ] {
    let r = std::panic::catch_unwind(|| {
      drop(berry::parse(src));
    });
    assert!(r.is_ok(), "panicked on {src:?}");
  }
}
