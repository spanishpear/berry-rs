//! The canonical dump written from the views must equal the dump of the
//! frozen reference, also when keys repeat (the views keep duplicates in
//! source order; the dump must apply 0.6 last-wins semantics), and the views'
//! own last-wins accessors must agree.

use berry_test::differential::{Outcome, candidate, check, reference};

const HEAD: &str = "# This file is generated by running \"yarn install\" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10\n\n";

fn assert_same(label: &str, body: &str) {
  let src = format!("{HEAD}{body}");
  let r = reference(&src);
  assert!(matches!(r, Outcome::Ok(_)), "{label}: reference must parse");
  let c = candidate(&src);
  if let Err(e) = check(&r, &c) {
    panic!("{label}: {e}");
  }
}

#[test]
fn duplicate_dependency_keys() {
  assert_same(
    "deps",
    "\"a@npm:1\":\n  version: 1\n  dependencies:\n    z: npm:1\n    \"@s/b\": npm:2\n    z: npm:3\n    \"@s/b\": npm:4\n    a: npm:5\n  languageName: node\n  linkType: hard\n",
  );
}

#[test]
fn duplicate_peer_keys() {
  assert_same(
    "peers",
    "\"a@npm:1\":\n  peerDependencies:\n    p: \"*\"\n    q: ^1\n    p: ^2\n  languageName: node\n",
  );
}

#[test]
fn duplicate_meta_keys() {
  assert_same(
    "dmeta",
    "\"a@npm:1\":\n  dependenciesMeta:\n    b:\n      built: true\n    c:\n      optional: true\n    b:\n      unplugged: false\n  peerDependenciesMeta:\n    p:\n      optional: true\n    p:\n      optional: false\n    \"@s/q\":\n      optional: true\n",
  );
}

#[test]
fn duplicate_bin_keys() {
  assert_same(
    "bin",
    "\"a@npm:1\":\n  bin:\n    t: ./t.js\n    a: ./a.js\n    t: ./t2.js\n",
  );
}

#[test]
fn repeated_blocks() {
  assert_same(
    "blocks",
    "\"a@npm:1\":\n  dependencies:\n    b: npm:1\n    c: npm:1\n  peerDependencies:\n    p: \"*\"\n  dependencies:\n    c: npm:2\n    d: npm:3\n  bin:\n    x: ./x\n  bin:\n    x: ./y\n  peerDependencies:\n    p: ^9\n",
  );
}

#[test]
fn repeated_scalar_properties() {
  assert_same(
    "scalars",
    "\"a@npm:1\":\n  version: 1\n  version: 2\n  resolution: \"a@npm:1\"\n  resolution: \"@s/a@npm:2\"\n  checksum: x\n  checksum: y\n  languageName: node\n  languageName: other\n  linkType: soft\n  linkType: hard\n  conditions: os=a\n  conditions: os=b\n",
  );
}

#[test]
fn duplicates_across_entries_are_independent() {
  assert_same(
    "entries",
    "\"a@npm:1\":\n  dependencies:\n    z: npm:1\n    z: npm:2\n\n\"b@npm:1\":\n  dependencies:\n    z: npm:3\n\n\"a@npm:1\":\n  version: 1\n",
  );
}

#[test]
fn view_accessors_apply_last_wins() {
  let src = format!(
    "{HEAD}\"a@npm:1\":\n  dependencies:\n    z: npm:1\n    \"@s/b\": npm:2\n    z: npm:3\n  bin:\n    t: ./1\n    t: ./2\n  dependenciesMeta:\n    z:\n      built: true\n    z:\n      built: false\n  peerDependencies:\n    p: \"*\"\n    p: ^1\n  peerDependenciesMeta:\n    p:\n      optional: true\n    p:\n      optional: false\n"
  );
  let lf = berry::parse(&src).unwrap();
  let e = lf.entry(0).unwrap();
  let deps: Vec<_> = e
    .dependencies()
    .iter()
    .map(|d| (d.ident().as_str(), d.range()))
    .collect();
  assert_eq!(deps, [("z", "npm:1"), ("@s/b", "npm:2"), ("z", "npm:3")]);
  assert_eq!(e.dependencies().get("z").unwrap().range(), "npm:3");
  let lw: Vec<_> = e
    .dependencies()
    .last_wins()
    .map(|d| d.to_string())
    .collect();
  assert_eq!(lw, ["@s/b@npm:2", "z@npm:3"]);
  assert_eq!(e.dependencies().lookup().get("z").unwrap().range(), "npm:3");
  assert_eq!(e.bin().get("t"), Some("./2"));
  assert_eq!(e.dependencies_meta().get("z").unwrap().built, Some(false));
  assert_eq!(e.peer_dependencies().get("p").unwrap().range(), "^1");
  assert!(!e.peer_dependencies_meta().get("p").unwrap().optional);
}
