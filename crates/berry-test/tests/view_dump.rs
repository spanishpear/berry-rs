//! Duplicate keys keep source order, and view accessors apply last-wins semantics.

const HEAD: &str = "# This file is generated by running \"yarn install\" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10\n\n";

#[test]
fn view_accessors_apply_last_wins() {
  let src = format!(
    "{HEAD}\"a@npm:1\":\n  dependencies:\n    z: npm:1\n    \"@s/b\": npm:2\n    z: npm:3\n  bin:\n    t: ./1\n    t: ./2\n  dependenciesMeta:\n    z:\n      built: true\n    z:\n      built: false\n  peerDependencies:\n    p: \"*\"\n    p: ^1\n  peerDependenciesMeta:\n    p:\n      optional: true\n    p:\n      optional: false\n"
  );
  let lf = berry::parse(&src).unwrap();
  let e = lf.entry(0).unwrap();
  let deps: Vec<_> = e
    .dependencies()
    .iter()
    .map(|d| (d.ident().as_str(), d.range()))
    .collect();
  assert_eq!(deps, [("z", "npm:1"), ("@s/b", "npm:2"), ("z", "npm:3")]);
  assert_eq!(e.dependencies().get("z").unwrap().range(), "npm:3");
  let lw: Vec<_> = e
    .dependencies()
    .last_wins()
    .map(|d| d.to_string())
    .collect();
  assert_eq!(lw, ["@s/b@npm:2", "z@npm:3"]);
  assert_eq!(e.dependencies().lookup().get("z").unwrap().range(), "npm:3");
  assert_eq!(e.bin().get("t"), Some("./2"));
  assert_eq!(e.dependencies_meta().get("z").unwrap().built, Some(false));
  assert_eq!(e.peer_dependencies().get("p").unwrap().range(), "^1");
  assert!(!e.peer_dependencies_meta().get("p").unwrap().optional);
}
